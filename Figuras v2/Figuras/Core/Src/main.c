/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  /* USER CODE BEGIN 2 */

  // Iniciar PWM
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);

  // Iniciar Encoders
  HAL_TIM_Encoder_Start(&htim2, TIM_CHANNEL_ALL);
  HAL_TIM_Encoder_Start(&htim4, TIM_CHANNEL_ALL);

  // Resetear contadores
  __HAL_TIM_SET_COUNTER(&htim2, 0);
  __HAL_TIM_SET_COUNTER(&htim4, 0);

  // Motores detenidos al arrancar
  MotorIzq_Detener();
  MotorDer_Detener();

  HAL_Delay(1000);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    // ---- Resetear contadores antes de cada avance ----
    __HAL_TIM_SET_COUNTER(&htim2, 0);
    __HAL_TIM_SET_COUNTER(&htim4, 0);

    // ---- KICKSTART: Arranque fuerte ----
    MotorIzq_Adelante(VELOCIDAD_KICKSTART);
    MotorDer_Adelante(VELOCIDAD_KICKSTART);
    HAL_Delay(TIEMPO_KICKSTART_MS);

    // ---- Bucle de avance controlado por encoders ----
    uint32_t tiempo_inicio = HAL_GetTick();

    while (1)
    {
        encoder_izq = (int32_t)__HAL_TIM_GET_COUNTER(&htim2);
        encoder_der = (int32_t)__HAL_TIM_GET_COUNTER(&htim4);

        // Condición 1: ambos encoders alcanzaron el objetivo
        if (encoder_izq >= PULSOS_POR_LADO && encoder_der >= PULSOS_POR_LADO)
        {
            MotorIzq_Detener();
            MotorDer_Detener();
            break;
        }

        // Condición 2: tiempo máximo superado (seguridad)
        if (HAL_GetTick() - tiempo_inicio > TIEMPO_MAXIMO_MS)
        {
            MotorIzq_Detener();
            MotorDer_Detener();
            break;
        }

        // Mover motores con compensación de velocidad
        MotorIzq_Adelante(VELOCIDAD_IZQ);
        MotorDer_Adelante(VELOCIDAD_DER);

        HAL_Delay(10);
    }

    // ---- Pausa antes de repetir la prueba ----
    HAL_Delay(3000);

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

